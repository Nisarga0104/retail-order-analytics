USE retail_order_analytics;


-- ============================================================
-- SECTION 1: PRODUCT AND ORDER ITEM EXPLORATION
-- ============================================================

-- BUSINESS QUESTION: What products were purchased in each order?
-- CONCEPTS: INNER JOIN, table aliases, and ORDER BY.

SELECT
    oi.order_item_id,
    p.product_name,
    c.category_name,
    oi.quantity,
    oi.unit_price,
    oi.discount_percent
FROM order_items oi

-- Match each order item to its product.
JOIN products p
    ON oi.product_id = p.product_id

-- Match each product to its category.
JOIN categories c
    ON p.category_id = c.category_id

ORDER BY oi.order_id;


-- BUSINESS QUESTION: What is the net revenue generated by each order item?
-- CONCEPTS: JOIN, arithmetic, ROUND(), and ORDER BY.

SELECT
    oi.order_item_id,
    o.order_id,
    p.product_name,
    oi.quantity,
    oi.unit_price,
    oi.discount_percent,

    -- Calculate revenue after applying the discount.
    ROUND(
        oi.quantity * oi.unit_price
        * (1 - oi.discount_percent / 100),
        2
    ) AS net_revenue

FROM order_items oi

JOIN orders o
    ON oi.order_id = o.order_id

JOIN products p
    ON oi.product_id = p.product_id

ORDER BY net_revenue DESC;


-- ============================================================
-- SECTION 2: PRODUCT AND CATEGORY REVENUE ANALYSIS
-- ============================================================

-- BUSINESS QUESTION: Which products generate the most revenue?
-- CONCEPTS: JOIN, SUM(), GROUP BY, ROUND(), and ORDER BY.

SELECT
    p.product_name,

    -- Calculate total discounted revenue for each product.
    ROUND(
        SUM(
            oi.quantity * oi.unit_price
            * (1 - oi.discount_percent / 100)
        ),
        2
    ) AS total_net_revenue

FROM order_items oi

JOIN products p
    ON oi.product_id = p.product_id

GROUP BY
    p.product_id,
    p.product_name

ORDER BY total_net_revenue DESC;


-- BUSINESS QUESTION: Which product categories generate the most revenue?
-- CONCEPTS: Multiple JOINs, SUM(), GROUP BY, ROUND(), and ORDER BY.

SELECT
    c.category_name,

    -- Add discounted revenue from all order items in each category.
    ROUND(
        SUM(
            oi.quantity * oi.unit_price
            * (1 - oi.discount_percent / 100)
        ),
        2
    ) AS total_net_revenue

FROM order_items oi

JOIN products p
    ON oi.product_id = p.product_id

JOIN categories c
    ON p.category_id = c.category_id

GROUP BY
    c.category_id,
    c.category_name

ORDER BY total_net_revenue DESC;


-- BUSINESS QUESTION: Which categories generate more than ₹10,000 in net revenue?
-- CONCEPTS: JOIN, SUM(), GROUP BY, HAVING, ROUND(), and ORDER BY.

SELECT
    c.category_name,

    ROUND(
        SUM(
            oi.quantity * oi.unit_price
            * (1 - oi.discount_percent / 100)
        ),
        2
    ) AS total_net_revenue

FROM order_items oi

JOIN products p
    ON oi.product_id = p.product_id

JOIN categories c
    ON p.category_id = c.category_id

GROUP BY
    c.category_id,
    c.category_name

-- Keep only categories whose revenue exceeds ₹10,000.
HAVING SUM(
    oi.quantity * oi.unit_price
    * (1 - oi.discount_percent / 100)
) > 10000

ORDER BY total_net_revenue DESC;


-- ============================================================
-- SECTION 3: CUSTOMER AND ORDER ANALYSIS
-- ============================================================

-- BUSINESS QUESTION: How much does each customer spend,
-- and how many orders have they placed?
-- CONCEPTS: JOIN, GROUP BY, COUNT(DISTINCT), SUM(), and ROUND().

SELECT
    c.customer_id,

    -- Combine the customer's first and last names.
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,

    COUNT(DISTINCT o.order_id) AS total_orders,

    -- Calculate the customer's total discounted revenue.
    ROUND(
        SUM(
            oi.quantity * oi.unit_price
            * (1 - oi.discount_percent / 100)
        ),
        2
    ) AS total_net_revenue

FROM customers c

JOIN orders o
    ON c.customer_id = o.customer_id

JOIN order_items oi
    ON o.order_id = oi.order_id

GROUP BY
    c.customer_id,
    c.first_name,
    c.last_name

ORDER BY total_net_revenue DESC;


-- BUSINESS QUESTION: What is the net value of each order?
-- CONCEPTS: JOIN, SUM(), GROUP BY, ROUND(), and ORDER BY.

SELECT
    o.order_id,
    o.order_date,
    o.order_status,

    -- Add discounted revenue from every item in the order.
    ROUND(
        SUM(
            oi.quantity * oi.unit_price
            * (1 - oi.discount_percent / 100)
        ),
        2
    ) AS order_net_revenue

FROM orders o

JOIN order_items oi
    ON o.order_id = oi.order_id

GROUP BY
    o.order_id,
    o.order_date,
    o.order_status

ORDER BY o.order_date DESC;


-- BUSINESS QUESTION: How many orders are in each status?
-- CONCEPTS: COUNT(), GROUP BY, and ORDER BY.

SELECT
    order_status,
    COUNT(*) AS total_orders
FROM orders
GROUP BY order_status
ORDER BY total_orders DESC;


-- BUSINESS QUESTION: What percentage of all orders belongs to each status?
-- CONCEPTS: COUNT(), GROUP BY, subquery, ROUND(), and percentage calculation.

SELECT
    order_status,
    COUNT(*) AS total_orders,

    -- Calculate each status's percentage of all orders.
    ROUND(
        COUNT(*) * 100.0
        / (SELECT COUNT(*) FROM orders),
        2
    ) AS percentage_of_orders

FROM orders

GROUP BY order_status

ORDER BY total_orders DESC;


-- ============================================================
-- SECTION 4: MONTHLY SALES AND PRODUCT PERFORMANCE
-- ============================================================

-- BUSINESS QUESTION: How many orders and how much net revenue
-- were generated in each month?

SELECT
    -- Convert the order date into a Year-Month label.
    DATE_FORMAT(o.order_date, '%Y-%m') AS order_month,

    COUNT(DISTINCT o.order_id) AS total_orders,

    -- Calculate revenue after applying item discounts.
    ROUND(
        SUM(
            oi.quantity * oi.unit_price
            * (1 - oi.discount_percent / 100)
        ),
        2
    ) AS total_net_revenue

FROM orders o

JOIN order_items oi
    ON o.order_id = oi.order_id

GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')

ORDER BY order_month ASC;


-- BUSINESS QUESTION: Which five products sold the most units?
-- CONCEPTS: JOIN, SUM(), GROUP BY, ORDER BY, and LIMIT.

SELECT
    p.product_name,

    -- Add quantities from all order items for each product.
    SUM(oi.quantity) AS total_units_sold

FROM order_items oi

JOIN products p
    ON oi.product_id = p.product_id

GROUP BY
    p.product_id,
    p.product_name

ORDER BY total_units_sold DESC

LIMIT 5;


-- BUSINESS QUESTION: Which three customers have the highest net revenue?
-- CONCEPTS: JOIN, SUM(), GROUP BY, ORDER BY, and LIMIT.

SELECT
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,

    ROUND(
        SUM(
            oi.quantity * oi.unit_price
            * (1 - oi.discount_percent / 100)
        ),
        2
    ) AS total_net_revenue

FROM customers c

JOIN orders o
    ON c.customer_id = o.customer_id

JOIN order_items oi
    ON o.order_id = oi.order_id

GROUP BY
    c.customer_id,
    c.first_name,
    c.last_name

ORDER BY total_net_revenue DESC

LIMIT 3;


-- BUSINESS QUESTION: Which products are priced above the overall average?
-- CONCEPTS: Subquery, AVG(), WHERE, and ORDER BY.

SELECT
    product_id,
    product_name,
    unit_price

FROM products

-- Compare each product price with the average product price.
WHERE unit_price > (
    SELECT AVG(unit_price)
    FROM products
)

ORDER BY unit_price DESC;


